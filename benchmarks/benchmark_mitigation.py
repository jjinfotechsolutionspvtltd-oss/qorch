"""Generate the QS-004 mitigation benchmark report (the M3 gate artifact).

Runs both mitigation techniques on the noisy local simulator and writes BENCHMARK.md with
raw-vs-mitigated numbers. Dependency-free; run from the orchestrator directory:

    PYTHONPATH=src python benchmarks/benchmark_mitigation.py
"""

from __future__ import annotations

from datetime import date
from pathlib import Path

from qorch import (
    Circuit,
    GateNoise,
    LocalSimulator,
    ReadoutNoise,
    expectation_z,
    zne_expectation,
)
from qorch.mitigation.readout import ReadoutMitigator

SEED = 7
SHOTS = 20000


def readout_benchmark() -> dict[str, float]:
    """Asymmetric readout error on a 50/50 state; measure total-variation distance to ideal."""
    p1_given0, p0_given1 = 0.05, 0.15
    ideal = {"0": 0.5, "1": 0.5}
    raw = LocalSimulator(
        seed=SEED, readout_noise=ReadoutNoise(p1_given0=p1_given0, p0_given1=p0_given1)
    ).run(Circuit(num_qubits=1).h(0), SHOTS)

    mitigator = ReadoutMitigator.from_calibration_matrix(
        labels=["0", "1"],
        matrix=[[1 - p1_given0, p0_given1], [p1_given0, 1 - p0_given1]],
    )
    mitigated = mitigator.apply(raw.counts)

    def tv(dist: dict[str, float]) -> float:
        return 0.5 * sum(abs(dist.get(k, 0.0) / SHOTS - ideal[k]) for k in ideal)

    return {
        "raw_err": tv({k: float(v) for k, v in raw.counts.items()}),
        "mitigated_err": tv(mitigated),
    }


def zne_benchmark() -> dict[str, float]:
    """Depolarizing gate noise on an identity-equivalent circuit; recover ⟨Z⟩ = 1 via ZNE."""
    circuit = Circuit(num_qubits=1).x(0).x(0).x(0).x(0)  # ideal ⟨Z⟩ = 1
    noisy = LocalSimulator(seed=SEED, gate_noise=GateNoise(depolarizing_prob=0.05))
    result = zne_expectation(noisy, circuit, expectation_z, scales=(1, 3, 5), shots=SHOTS)
    return {
        "raw_err": abs(result.raw - 1.0),
        "mitigated_err": abs(result.mitigated - 1.0),
        "raw": result.raw,
        "mitigated": result.mitigated,
    }


def _pct(before: float, after: float) -> str:
    if before == 0:
        return "n/a"
    return f"{(1 - after / before) * 100:.0f}%"


def render_report(readout: dict[str, float], zne: dict[str, float]) -> str:
    return f"""# QS-004 — Mitigation Benchmark

_Generated by `benchmarks/benchmark_mitigation.py` · {date.today().isoformat()} · \
seed={SEED}, shots={SHOTS:,}_

The point of the orchestration layer in one table: the **same circuit**, run raw vs. routed
through QS-004's mitigation, gets measurably closer to the ideal noise-free result.

## 1. Readout-error mitigation (calibration-matrix inversion)

Asymmetric readout error (P(1|0)=0.05, P(0|1)=0.15) on a true 50/50 superposition.
Error = total-variation distance to the ideal distribution (lower is better).

| | Error vs. ideal |
|---|---|
| Raw (noisy) | {readout['raw_err']:.4f} |
| **Mitigated** | **{readout['mitigated_err']:.4f}** |
| Error reduction | **{_pct(readout['raw_err'], readout['mitigated_err'])}** |

## 2. Zero-noise extrapolation (unitary folding)

Depolarizing gate noise (p=0.05) on an identity-equivalent circuit whose ideal ⟨Z⟩ = 1.
Error = |measured - 1| (lower is better).

| | ⟨Z⟩ | Error vs. ideal |
|---|---|---|
| Raw (noise scale 1) | {zne['raw']:.4f} | {zne['raw_err']:.4f} |
| **ZNE-extrapolated** | {zne['mitigated']:.4f} | **{zne['mitigated_err']:.4f}** |
| Error reduction | | **{_pct(zne['raw_err'], zne['mitigated_err'])}** |

---

Both numbers are produced end-to-end on the dependency-free `LocalSimulator`; the identical
code path runs against real hardware via `QiskitBackend` (M2). Reproduce with the command in
this script's docstring.
"""


_MIN_READOUT_REDUCTION_PCT = 40.0
_MIN_ZNE_REDUCTION_PCT = 20.0


def main() -> None:
    readout = readout_benchmark()
    zne = zne_benchmark()
    report = render_report(readout, zne)
    out = Path(__file__).resolve().parent.parent / "BENCHMARK.md"
    out.write_text(report, encoding="utf-8")
    # ASCII summary only — the full report (with unicode) lives in the UTF-8 file.
    print("Readout mitigation: err {:.4f} -> {:.4f}  ({} reduction)".format(
        readout["raw_err"], readout["mitigated_err"],
        _pct(readout["raw_err"], readout["mitigated_err"])))
    print("ZNE                : err {:.4f} -> {:.4f}  ({} reduction)".format(
        zne["raw_err"], zne["mitigated_err"],
        _pct(zne["raw_err"], zne["mitigated_err"])))
    print(f"Wrote {out}")

    # Auto-regression checks
    exit_code = 0
    if readout["raw_err"] > 0:
        pct = (1 - readout["mitigated_err"] / readout["raw_err"]) * 100
        if pct < _MIN_READOUT_REDUCTION_PCT:
            print(f"FAIL: Readout reduction {pct:.1f}% < {_MIN_READOUT_REDUCTION_PCT:.0f}%")
            exit_code = 1
    if zne["raw_err"] > 0:
        pct = (1 - zne["mitigated_err"] / zne["raw_err"]) * 100
        if pct < _MIN_ZNE_REDUCTION_PCT:
            print(f"FAIL: ZNE reduction {pct:.1f}% < {_MIN_ZNE_REDUCTION_PCT:.0f}%")
            exit_code = 1
    if exit_code:
        print("Benchmark regression threshold(s) not met")
    raise SystemExit(exit_code)


if __name__ == "__main__":
    main()
